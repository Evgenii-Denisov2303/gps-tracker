def test_tcp_fragmentation_coalescing_ack_and_revocation(store):
    async def run():
        receiver = Receiver(store)
        server = await asyncio.start_server(receiver.handle, '127.0.0.1', 0)
        async with server:
            reader, writer = await asyncio.open_connection('127.0.0.1', server.sockets[0].getsockname()[1])
            handshake = ntcb(b'*>S:'+IMEI.encode(), receiver=1, sender=0)
            for b in handshake:
                writer.write(bytes([b]))
                await writer.drain()
                await asyncio.sleep(0)
            assert (await read_frame(reader, None))[1][2] == b'*<S'
            writer.write(ntcb(negotiation(), receiver=1, sender=0) + frame(record()))
            await writer.drain()
            assert (await read_frame(reader, None))[1][2] == b'*<FLEX\xb0\x0a\x0a'
            ack = await reader.readexactly(4)
            assert ack[:3] == b'~A\x01'
            with store.factory() as db:
                assert db.scalar(select(func.count()).select_from(LocationPoint)) == 1
                db.get(Device, 1).active = False
                db.commit()
            writer.write(frame(record()))
            await writer.drain()
            assert await asyncio.wait_for(reader.read(), 2) == b''
            writer.close()
            await writer.wait_closed()
    asyncio.run(run())


def test_no_ack_when_database_fails():
    class FailingStore:
        def authorize(self, imei):
            pass
        def save(self, imei, rows):
            raise RuntimeError('database unavailable')
    async def run():
        receiver = Receiver(FailingStore())
        server = await asyncio.start_server(receiver.handle, '127.0.0.1', 0)
        async with server:
            r, w = await asyncio.open_connection('127.0.0.1', server.sockets[0].getsockname()[1])
            w.write(ntcb(b'*>S:'+IMEI.encode(), 1, 0) + ntcb(negotiation(), 1, 0) + frame(record()))
            await w.drain()
            await read_frame(r, None)
            await read_frame(r, None)
            assert await asyncio.wait_for(r.read(), 2) == b''
            w.close()
            await w.wait_closed()
    asyncio.run(run())


