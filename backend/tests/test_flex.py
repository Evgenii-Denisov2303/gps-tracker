def negotiation(fields=RECOMMENDED_FIELDS, version=10):
    bits = {10: 69, 20: 122, 30: 255}[version]
    mask = bytearray((bits+7)//8)
    for n in fields:
        mask[(n-1)//8] |= 0x80 >> ((n-1) % 8)
    return b'*>FLEX\xb0' + bytes([version, version, bits]) + mask


def record(timestamp=None, **overrides):
    stamp = int((timestamp or utcnow()).timestamp())
    fields = {1: 100, 2: 10, 3: stamp, 4: 0, 5: 8, 7: 24, 8: 8*4+3,
              9: stamp, 10: 33000000, 11: 29400000, 13: 30., 14: 90, 19: 12400, 20: 4000}
    fields.update({int(k): v for k, v in overrides.items()})
    return fields


def frame(fields, command=b'A', profile=None):
    profile = profile or Profile(negotiation())
    prefix = b'~'+command+ (b'\x01' if command == b'A' else struct.pack('<I', fields[1]) if command == b'T' else b'')
    body = prefix + profile.layout.pack(*(fields[n] for n in profile.fields))
    return body + bytes([crc8(body)])


