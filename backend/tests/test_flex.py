def test_manufacturer_published_vector():
    # Official manual v6, pp118–119. Independent bytes, not generated by our encoder.
    packet = bytes.fromhex('404e544301000000000000001a001b192a3e464c4558b014147af2002000000000000000000000000000')
    profile = Profile(packet[16:])
    assert profile.fields == [1, 2, 3, 4, 7, 19]
    assert profile.ready is False  # Request downgrade to base protocol.
    profile = Profile(negotiation(profile.fields))
    records, ack = profile.records(bytes.fromhex('7e41011e000000b017e11d7456001f142f24'))
    assert records == [{1: 30, 2: 6064, 3: 1450450401, 4: 0, 7: 31, 19: 12052}]
    assert ack[:3] == b'~A\x01'


@pytest.mark.parametrize('command', [b'A', b'T', b'C'])
def test_flex_messages_and_corruption(command):
    p = Profile(negotiation())
    fields = record()
    packet = frame(fields, command)
    assert p.records(packet)[0] == [fields]
    with pytest.raises(ProtocolError):
        p.records(packet[:-1] + bytes([packet[-1] ^ 1]))


def test_profile_rejects_unknown_fields_and_lengths():
    for payload in (negotiation((1, 2, 3, 21)), negotiation()[:-1], b'garbage'):
        with pytest.raises(ProtocolError):
            Profile(payload)
    assert not Profile(negotiation(version=30)).ready


def test_durable_ingestion_replays_and_archive_do_not_replace_live(store):
    current = record()
    store.save(IMEI, [current, current])
    archive = record(utcnow()-timedelta(days=1), **{'1': 99, '19': 11000})
    store.save(IMEI, [archive])
    with store.factory() as db:
        assert db.scalar(select(func.count()).select_from(LocationPoint)) == 2
        assert db.scalar(select(func.count()).select_from(HardwareRecord)) == 2
        d = db.get(Device, 1)
        assert d.health['main_voltage'] == 12.4
        assert d.health['satellites'] == 8
        p = db.scalar(select(LocationPoint))
        assert p.accuracy is None and p.latitude == 55 and p.longitude == 49


